create or replace view public.acompanhamento_painel
with (security_invoker = true)
as
select
  r.*,
  coalesce(p.total_previsto, 0)::numeric(14,2) as total_previsto,
  coalesce(p.total_pago, 0)::numeric(14,2) as total_pago,
  greatest(coalesce(p.total_previsto, r.valor_acordado) - coalesce(p.total_pago, 0), 0)::numeric(14,2) as saldo_aberto,
  coalesce(p.quantidade_pagamentos, 0)::integer as quantidade_pagamentos,
  coalesce(p.pagamentos_pagos, 0)::integer as pagamentos_pagos,
  p.proximo_vencimento,
  coalesce(p.pagamentos_atrasados, 0)::integer as pagamentos_atrasados,
  case
    when r.status = 'cancelado' then 'cancelado'
    when coalesce(p.quantidade_pagamentos, 0) = 0 then 'sem_pagamentos'
    when coalesce(p.pagamentos_atrasados, 0) > 0 then 'atrasado'
    when coalesce(p.total_pago, 0) >= coalesce(nullif(p.total_previsto, 0), r.valor_acordado) then 'pago'
    when coalesce(p.total_pago, 0) > 0 then 'parcial'
    else 'pendente'
  end as situacao_financeira
from public.acompanhamento_registros r
left join lateral (
  select
    sum(case when ap.status <> 'cancelado' then ap.valor_previsto else 0 end) as total_previsto,
    sum(case when ap.status = 'pago' then greatest(ap.valor_pago, ap.valor_previsto) else ap.valor_pago end) as total_pago,
    count(*) filter (where ap.status <> 'cancelado') as quantidade_pagamentos,
    count(*) filter (where ap.status = 'pago') as pagamentos_pagos,
    min(ap.vencimento) filter (where ap.status not in ('pago', 'cancelado')) as proximo_vencimento,
    count(*) filter (where ap.status not in ('pago', 'cancelado') and ap.vencimento < current_date) as pagamentos_atrasados
  from public.acompanhamento_pagamentos ap
  where ap.registro_id = r.id
) p on true
where r.arquivado_em is null;

