create table if not exists public.acompanhamento_registros (
  id uuid primary key default gen_random_uuid(),
  codigo bigint generated by default as identity,
  controle text not null default 'marketing',
  ano_referencia integer not null default extract(year from current_date)::integer,
  fornecedor text,
  fornecedor_codigo text,
  categoria text not null default 'outro',
  titulo text not null,
  descricao text,
  referencia text,
  responsavel_id uuid references public.colaboradores(id) on delete set null,
  contato_nome text,
  contato_email text,
  contato_telefone text,
  status text not null default 'rascunho',
  prioridade text not null default 'normal',
  data_inicio date,
  data_fim date,
  valor_acordado numeric(14,2) not null default 0,
  centro_custo text,
  numero_documento text,
  tags text[] not null default '{}'::text[],
  observacoes text,
  origem_importacao text,
  linha_origem integer,
  fingerprint text,
  dados_originais jsonb not null default '{}'::jsonb,
  criado_por uuid references public.colaboradores(id) on delete set null,
  atualizado_por uuid references public.colaboradores(id) on delete set null,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  arquivado_em timestamptz,
  constraint acompanhamento_controle_valido check (controle in ('marcos', 'marketing')),
  constraint acompanhamento_ano_valido check (ano_referencia between 2000 and 2200),
  constraint acompanhamento_titulo_valido check (length(trim(titulo)) > 0),
  constraint acompanhamento_valor_valido check (valor_acordado >= 0),
  constraint acompanhamento_status_valido check (
    status in ('rascunho', 'negociacao', 'aprovado', 'em_andamento', 'concluido', 'cancelado')
  ),
  constraint acompanhamento_prioridade_valida check (prioridade in ('baixa', 'normal', 'alta', 'urgente')),
  constraint acompanhamento_periodo_valido check (data_fim is null or data_inicio is null or data_fim >= data_inicio)
);

create unique index if not exists idx_acompanhamento_codigo
  on public.acompanhamento_registros(codigo);
create unique index if not exists idx_acompanhamento_fingerprint
  on public.acompanhamento_registros(fingerprint)
  where fingerprint is not null and arquivado_em is null;
create index if not exists idx_acompanhamento_filtros
  on public.acompanhamento_registros(controle, ano_referencia, status, categoria)
  where arquivado_em is null;
create index if not exists idx_acompanhamento_fornecedor
  on public.acompanhamento_registros(lower(fornecedor))
  where arquivado_em is null;
create index if not exists idx_acompanhamento_responsavel
  on public.acompanhamento_registros(responsavel_id, atualizado_em desc)
  where arquivado_em is null;

create table if not exists public.acompanhamento_pagamentos (
  id uuid primary key default gen_random_uuid(),
  registro_id uuid references public.acompanhamento_registros(id) on delete cascade not null,
  parcela integer not null default 1,
  descricao text,
  valor_previsto numeric(14,2) not null default 0,
  valor_pago numeric(14,2) not null default 0,
  vencimento date,
  pago_em date,
  status text not null default 'previsto',
  forma_pagamento text,
  favorecido text,
  numero_documento text,
  observacoes text,
  fingerprint text,
  criado_por uuid references public.colaboradores(id) on delete set null,
  atualizado_por uuid references public.colaboradores(id) on delete set null,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  constraint acompanhamento_pagamento_parcela_valida check (parcela > 0),
  constraint acompanhamento_pagamento_valores_validos check (valor_previsto >= 0 and valor_pago >= 0),
  constraint acompanhamento_pagamento_status_valido check (
    status in ('previsto', 'solicitado', 'aprovado', 'agendado', 'pago', 'cancelado')
  )
);

create unique index if not exists idx_acompanhamento_pagamento_fingerprint
  on public.acompanhamento_pagamentos(registro_id, fingerprint)
  where fingerprint is not null;
create index if not exists idx_acompanhamento_pagamentos_vencimento
  on public.acompanhamento_pagamentos(vencimento, status);
create index if not exists idx_acompanhamento_pagamentos_registro
  on public.acompanhamento_pagamentos(registro_id, parcela);

create table if not exists public.acompanhamento_anexos (
  id uuid primary key default gen_random_uuid(),
  registro_id uuid references public.acompanhamento_registros(id) on delete cascade not null,
  pagamento_id uuid references public.acompanhamento_pagamentos(id) on delete cascade,
  nome text not null,
  caminho text not null unique,
  mime_type text,
  tamanho_bytes bigint,
  tipo text not null default 'documento',
  criado_por uuid references public.colaboradores(id) on delete set null,
  criado_em timestamptz not null default now(),
  constraint acompanhamento_anexo_nome_valido check (length(trim(nome)) > 0),
  constraint acompanhamento_anexo_tipo_valido check (tipo in ('contrato', 'boleto', 'nota_fiscal', 'comprovante', 'proposta', 'documento')),
  constraint acompanhamento_anexo_tamanho_valido check (tamanho_bytes is null or tamanho_bytes >= 0)
);

create index if not exists idx_acompanhamento_anexos_registro
  on public.acompanhamento_anexos(registro_id, criado_em desc);

create table if not exists public.acompanhamento_atividades (
  id bigint generated by default as identity primary key,
  registro_id uuid references public.acompanhamento_registros(id) on delete cascade not null,
  pagamento_id uuid references public.acompanhamento_pagamentos(id) on delete cascade,
  ator_id uuid references public.colaboradores(id) on delete set null,
  tipo text not null,
  resumo text not null,
  detalhes jsonb not null default '{}'::jsonb,
  criado_em timestamptz not null default now()
