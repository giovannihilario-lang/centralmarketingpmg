create index if not exists idx_acompanhamento_atividades_registro
  on public.acompanhamento_atividades(registro_id, criado_em desc);
create index if not exists idx_acompanhamento_atividades_recentes
  on public.acompanhamento_atividades(criado_em desc);

create table if not exists public.acompanhamento_importacoes (
  id uuid primary key default gen_random_uuid(),
  controle text not null,
  ano_referencia integer,
  nome_arquivo text not null,
  total_linhas integer not null default 0,
  linhas_criadas integer not null default 0,
  linhas_atualizadas integer not null default 0,
  linhas_ignoradas integer not null default 0,
  erros jsonb not null default '[]'::jsonb,
  criado_por uuid references public.colaboradores(id) on delete set null,
  criado_em timestamptz not null default now(),
  constraint acompanhamento_importacao_controle_valido check (controle in ('marcos', 'marketing'))
);

