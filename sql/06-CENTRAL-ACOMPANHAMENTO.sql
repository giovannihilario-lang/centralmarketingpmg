create or replace function public.salvar_acompanhamento_v1(
  p_registro_id uuid,
  p_dados jsonb
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_ator uuid := public.meu_colaborador_id();
  v_id uuid := p_registro_id;
  v_titulo text := trim(coalesce(p_dados ->> 'titulo', ''));
  v_controle text := coalesce(nullif(p_dados ->> 'controle', ''), 'marketing');
  v_antes jsonb;
begin
  if v_ator is null then raise exception 'Colaborador nao encontrado ou inativo'; end if;
  if v_titulo = '' then raise exception 'O titulo e obrigatorio'; end if;
  if v_controle not in ('marcos', 'marketing') then raise exception 'Controle invalido'; end if;

  if v_id is null then
    insert into public.acompanhamento_registros (
      controle, ano_referencia, fornecedor, fornecedor_codigo, categoria, titulo,
      descricao, referencia, responsavel_id, contato_nome, contato_email,
      contato_telefone, status, prioridade, data_inicio, data_fim, valor_acordado,
      centro_custo, numero_documento, tags, observacoes, origem_importacao,
      linha_origem, fingerprint, dados_originais, criado_por, atualizado_por
    ) values (
      v_controle,
      coalesce((p_dados ->> 'ano_referencia')::integer, extract(year from current_date)::integer),
      nullif(trim(p_dados ->> 'fornecedor'), ''),
      nullif(trim(p_dados ->> 'fornecedor_codigo'), ''),
      coalesce(nullif(trim(p_dados ->> 'categoria'), ''), 'outro'),
      v_titulo,
      nullif(trim(p_dados ->> 'descricao'), ''),
      nullif(trim(p_dados ->> 'referencia'), ''),
      nullif(p_dados ->> 'responsavel_id', '')::uuid,
      nullif(trim(p_dados ->> 'contato_nome'), ''),
      nullif(trim(p_dados ->> 'contato_email'), ''),
      nullif(trim(p_dados ->> 'contato_telefone'), ''),
      coalesce(nullif(p_dados ->> 'status', ''), 'rascunho'),
      coalesce(nullif(p_dados ->> 'prioridade', ''), 'normal'),
      nullif(p_dados ->> 'data_inicio', '')::date,
      nullif(p_dados ->> 'data_fim', '')::date,
      greatest(coalesce(nullif(p_dados ->> 'valor_acordado', '')::numeric, 0), 0),
      nullif(trim(p_dados ->> 'centro_custo'), ''),
      nullif(trim(p_dados ->> 'numero_documento'), ''),
      coalesce(array(select jsonb_array_elements_text(coalesce(p_dados -> 'tags', '[]'::jsonb))), '{}'::text[]),
      nullif(trim(p_dados ->> 'observacoes'), ''),
      nullif(trim(p_dados ->> 'origem_importacao'), ''),
      nullif(p_dados ->> 'linha_origem', '')::integer,
      nullif(trim(p_dados ->> 'fingerprint'), ''),
      coalesce(p_dados -> 'dados_originais', '{}'::jsonb),
      v_ator, v_ator
    ) returning id into v_id;

    insert into public.acompanhamento_atividades(registro_id, ator_id, tipo, resumo, detalhes)
    values (v_id, v_ator, 'criado', 'criou o acompanhamento', jsonb_build_object('controle', v_controle));
  else
    select to_jsonb(r) into v_antes
    from public.acompanhamento_registros r
    where r.id = v_id and r.arquivado_em is null;
    if v_antes is null then raise exception 'Acompanhamento nao encontrado'; end if;

    update public.acompanhamento_registros set
      controle = v_controle,
      ano_referencia = coalesce((p_dados ->> 'ano_referencia')::integer, ano_referencia),
      fornecedor = nullif(trim(p_dados ->> 'fornecedor'), ''),
      fornecedor_codigo = nullif(trim(p_dados ->> 'fornecedor_codigo'), ''),
      categoria = coalesce(nullif(trim(p_dados ->> 'categoria'), ''), 'outro'),
      titulo = v_titulo,
      descricao = nullif(trim(p_dados ->> 'descricao'), ''),
      referencia = nullif(trim(p_dados ->> 'referencia'), ''),
      responsavel_id = nullif(p_dados ->> 'responsavel_id', '')::uuid,
      contato_nome = nullif(trim(p_dados ->> 'contato_nome'), ''),
      contato_email = nullif(trim(p_dados ->> 'contato_email'), ''),
      contato_telefone = nullif(trim(p_dados ->> 'contato_telefone'), ''),
      status = coalesce(nullif(p_dados ->> 'status', ''), status),
      prioridade = coalesce(nullif(p_dados ->> 'prioridade', ''), prioridade),
      data_inicio = nullif(p_dados ->> 'data_inicio', '')::date,
      data_fim = nullif(p_dados ->> 'data_fim', '')::date,
      valor_acordado = greatest(coalesce(nullif(p_dados ->> 'valor_acordado', '')::numeric, 0), 0),
      centro_custo = nullif(trim(p_dados ->> 'centro_custo'), ''),
      numero_documento = nullif(trim(p_dados ->> 'numero_documento'), ''),
      tags = coalesce(array(select jsonb_array_elements_text(coalesce(p_dados -> 'tags', '[]'::jsonb))), '{}'::text[]),
      observacoes = nullif(trim(p_dados ->> 'observacoes'), ''),
      atualizado_por = v_ator
    where id = v_id;

    insert into public.acompanhamento_atividades(registro_id, ator_id, tipo, resumo, detalhes)
    values (v_id, v_ator, 'editado', 'atualizou o acompanhamento', jsonb_build_object('antes', v_antes));
  end if;

  return v_id;
end;
$$;

